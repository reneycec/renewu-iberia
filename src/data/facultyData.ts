const FACULTY_STORAGE_KEY = "renewu_faculty_members_v2";

export function getStoredFaculty(): FacultyMember[] {
  try {
    const data = localStorage.getItem(FACULTY_STORAGE_KEY);
    if (data) {
      const parsed = JSON.parse(data);
      if (Array.isArray(parsed) && parsed.length >= DEFAULT_FACULTY.length) {
        return parsed;
      }
    }
  } catch (e) {
    console.error("Error reading faculty data from localStorage:", e);
  }
  // Auto-persist and return DEFAULT_FACULTY on first load or cache upgrade
  saveStoredFaculty(DEFAULT_FACULTY);
  return DEFAULT_FACULTY;
}

export function saveStoredFaculty(faculty: FacultyMember[]) {
  try {
    localStorage.setItem(FACULTY_STORAGE_KEY, JSON.stringify(faculty));
  } catch (e) {
    console.error("Error saving faculty data to localStorage:", e);
  }
}

export function getFacultyByName(name: string): FacultyMember | undefined {
  const all = getStoredFaculty();
  const normalizedSearch = name.toLowerCase().replace(/^(dr\.|prof\.|mstro\.)\s*/i, "").trim();
  return all.find((f) => {
    const normName = f.name.toLowerCase().replace(/^(dr\.|prof\.|mstro\.)\s*/i, "").trim();
    return normName.includes(normalizedSearch) || normalizedSearch.includes(normName);
  });
}
